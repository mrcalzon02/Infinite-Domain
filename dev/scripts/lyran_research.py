def stairwell_holes(rect: tuple[int, int, int, int], margin: int = 0) -> set[tuple[int, int]]:
    """Footprint of a vertical shaft, optionally grown by a margin.

    The margin exists because `encased_stairwell` builds its landings
    `landing_depth` blocks *beyond* the run it was given, so reserving only
    the nominal rect would let a prop land on a stair landing.
    """
    x1, z1, x2, z2 = rect
    return {
        (x, z)
        for x in range(x1 - margin, x2 + margin + 1)
        for z in range(z1 - margin, z2 + margin + 1)
    }


def solid_at(t: Template, x: int, y: int, z: int) -> bool:
    """True when a real, non-air block has actually been placed at this cell.

    Every prop is guarded on this: furniture needs a floor under it and a
    hanging lantern needs a ceiling over it.  Without the guard, a prop
    placed where a stair or the ascent shaft later cut the slab away becomes
    a floating block — which is precisely what check_structural_connectivity
    exists to catch.
    """
    entry = t.blocks.get((x, y, z))
    if entry is None:
        return False
    return t.palette[entry[0]]["Name"] != "minecraft:air"


def build_stairwell(t: Template, rect: tuple[int, int, int, int], y: int) -> None:
    """One straight 8-tread encased run carrying a full level of pitch.

    The run is cut through slabs the shell pass already placed, rather than
    through pre-punched holes: `encased_stairwell` clears three blocks of
    headroom over every tread, and that is exactly what opens this level's
    ceiling and the next level's floor — only where the stair physically
    passes.  Pre-holing the whole rect instead left an eleven-block pit in
    the floor of the level above, which is why it is not done that way.

    Treads run y+1..y+8; the top landing plate lands at y+8, the floor plane
    of the level above.
    """
    x1, z1, x2, z2 = rect
    cx = (x1 + x2) // 2
    V2.encased_stairwell(t, cx, y + 1, z1 + 2, 8, "south",
                         block="minecraft:blackstone_stairs", wall=WALL, width=2, landing_depth=2)
    # Level plate at the stair head.  backed_sign guarantees a backing block,
    # but a single backing block floating in the middle of a room is itself a
    # connectivity failure — so the backing is a full pilaster from the floor.
    sx, sz = cx + 2, z1 + 1
    t.fill((sx, y + 1, sz - 1), (sx, y + 6, sz - 1), WALL)
    V2.backed_sign(t, sx, y + 3, sz, "south", SIGN, backing=WALL)


def build_ascent_shaft(t: Template) -> None:
    """Armoured ladder climb from the Anchorage roof to a bastion head that
    stands clear of the Y=64 lava sea, and is the only opening in the envelope."""
    x1, z1, x2, z2 = SHAFT_RECT
    top_y = LEVELS[-1]["y"] + PITCH  # 40 — the Anchorage ceiling plane
    cx, cz = (x1 + x2) // 2, (z1 + z2) // 2

    # Two-thick armoured casing all the way up.
    # Casing starts at the Anchorage ceiling plane.  Running it down through
    # the Anchorage interior instead builds a five-by-five tube straight
    # through the arrival level, walling the ladder off from the stair hall it
    # is supposed to open onto.
    for y in range(top_y - 1, SHAFT_TOP + 1):
        for x in range(x1 - 1, x2 + 2):
            for z in range(z1 - 1, z2 + 2):
                on_skin = x in (x1 - 1, x1, x2, x2 + 1) or z in (z1 - 1, z1, z2, z2 + 1)
                if on_skin:
                    t.set(x, y, z, WALL if (x + z + y) % 11 else WALL_CRACKED)
    # Hollow core.
    t.clear((x1 + 1, LEVELS[-1]["y"] + 1, z1 + 1), (x2 - 1, SHAFT_TOP, z2 - 1))

    # Ladder run with rest landings every eight blocks.  It starts on the
    # Anchorage floor, not at the Anchorage ceiling: a climb that stops one
    # level short leaves arrivals with an unannounced six-block drop.
    y = LEVELS[-1]["y"] + 1
    while y < SHAFT_TOP - 1:
        run = min(8, SHAFT_TOP - 1 - y)
        V2.ladder_shaft(t, cx, y, z1 + 1, run, "south", backing=WALL)
        y += run
        if y < SHAFT_TOP - 2:
            # A rest landing, with a two-cell opening: the ladder column plus
            # the cell a climber steps off onto.  A one-cell hole plugged by
            # the ladder block itself reads to the room-composition check as a
            # sealed compartment, because a ladder is not air.
            for x in range(x1 + 1, x2):
                for z in range(z1 + 1, z2):
                    if (x, z) not in ((cx, z1 + 1), (cx, z1 + 2)):
                        t.set(x, y, z, "minecraft:blackstone")
            t.clear((cx, y, z1 + 1), (cx, y, z1 + 2))

    # Bastion head: a parapet standing above the lava, so the site reads as a
    # landmark from a distance instead of a hole in the floor.
    for x in range(x1 - 2, x2 + 3):
        for z in range(z1 - 2, z2 + 3):
            ring = x in (x1 - 2, x2 + 2) or z in (z1 - 2, z2 + 2)
            if ring:
                t.fill((x, SHAFT_TOP - 3, z), (x, SHAFT_TOP - 1, z), WALL)
            elif not (x1 < x < x2 and z1 < z < z2):
                t.set(x, SHAFT_TOP - 3, z, FLOOR_HALL)
    for cxx, czz in ((x1 - 2, z1 - 2), (x2 + 2, z1 - 2), (x1 - 2, z2 + 2), (x2 + 2, z2 + 2)):
        t.fill((cxx, SHAFT_TOP - 3, czz), (cxx, SHAFT_TOP, czz), WALL_CHISEL)
        t.set(cxx, SHAFT_TOP, czz, LAMP_PUBLIC, hanging="false", waterlogged="false")
    V2.backed_sign(t, cx, SHAFT_TOP - 2, z1 - 1, "north", SIGN, backing=WALL)


