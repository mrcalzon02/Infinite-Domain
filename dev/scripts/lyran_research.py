    def spot(i: int) -> tuple[int, int]:
        return inner[i % len(inner)]

    def standable(px: int, pz: int) -> bool:
        """A prop needs a real floor beneath it and clear air at its own cell."""
        return solid_at(t, px, y, pz) and not solid_at(t, px, y + 1, pz)

    # Every room gets light, hung from its own ceiling — but only where a
    # ceiling still exists after circulation cut through the slabs.
    lamp = LAMP_BY_KIND.get(kind, LAMP_PUBLIC)
    for i in range(max(1, len(cells) // 18)):
        lx, lz = spot(i * 7 + 3)
        if not solid_at(t, lx, y + 7, lz) or solid_at(t, lx, y + 6, lz):
            continue
        if lamp == LAMP_FARM:
            t.set(lx, y + 6, lz, LAMP_FARM)
        else:
            t.set(lx, y + 6, lz, lamp, hanging="true", waterlogged="false")

