def build_gate_chamber(t: Template, plan: Plan) -> set[tuple[int, int]]:
    """Room 21 on the Concourse: the End portal on a dais over a lava well,
    open to a gallery ring on the Habitation level above.

    Returns the cells whose Habitation-level floor slab must be omitted.
    """
    y = LEVEL_BY_KEY["concourse"]["y"]
    cells = plan.rooms[21]["cells"]
    x1, z1, x2, z2 = plan.rooms[21]["bounds"]
    cx, cz = 35, 43  # measured centre of the printed nine-block circle

    # Lava well under a raised dais — the aperture was found in the rock and
    # the colony built the floor around it.
    t.fill((cx - 3, y, cz - 3), (cx + 3, y, cz + 3), "minecraft:polished_blackstone_bricks")
    t.fill((cx - 1, y, cz - 1), (cx + 1, y, cz + 1), "minecraft:lava", level="0")
    t.fill((cx - 2, y + 1, cz - 2), (cx + 2, y + 1, cz + 2), "minecraft:air")

    # Twelve end portal frames around the 3x3 aperture.  Four already hold the
    # colony's own eyes — four hundred years of the Egress Programme's total
    # progress — leaving the rest for the player.
    seated = {(cx - 1, cz - 2), (cx + 1, cz - 2), (cx - 2, cz + 1), (cx + 2, cz - 1)}
    frames = []
    for d in (-1, 0, 1):
        frames.append(((cx + d, cz - 2), "south"))
        frames.append(((cx + d, cz + 2), "north"))
        frames.append(((cx - 2, cz + d), "east"))
        frames.append(((cx + 2, cz + d), "west"))
    for (fx, fz), facing in frames:
        t.set(fx, y + 1, fz, "minecraft:end_portal_frame", facing=facing,
              eye="true" if (fx, fz) in seated else "false")

    # Walkway ring, monitoring stations and the chamber's own lighting.
    for x, z in cells:
        if abs(x - cx) <= 2 and abs(z - cz) <= 2:
            continue
        t.set(x, y, z, FLOOR_HALL)
    for wx, wz, facing in wall_adjacent_of(cells, plan)[::3]:
        t.set(wx, y + 1, wz, "minecraft:lodestone")
    for lx, lz in ((cx - 4, cz), (cx + 4, cz), (cx, cz - 4), (cx, cz + 4)):
        if (lx, lz) in cells:
            t.set(lx, y + 6, lz, LAMP_PUBLIC, hanging="true", waterlogged="false")

    # Double height: pierce the Concourse ceiling across the chamber, and hand
    # back the footprint so the Habitation floor slab is omitted there too.
    void = {(x, z) for x, z in cells if abs(x - cx) <= 3 and abs(z - cz) <= 3}
    for x, z in void:
        t.set(x, y + 7, z, "minecraft:air")
    return void


def build_gate_gallery(t: Template, plan: Plan, void: set[tuple[int, int]]) -> None:
    """Habitation-level ring around the Gate void: a real balustrade, not a hole."""
    y = LEVEL_BY_KEY["habitation"]["y"]
    cells = plan.rooms[21]["cells"]
    for x, z in cells:
        if (x, z) in void:
            continue
        t.set(x, y, z, FLOOR_HALL)
    for x, z in void:
        for dx, dz in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            nx, nz = x + dx, z + dz
            if (nx, nz) in cells and (nx, nz) not in void:
                t.set(nx, y + 1, nz, "minecraft:polished_blackstone_slab", type="bottom", waterlogged="false")


