def build_level_shell(t: Template, plan: Plan, level: dict, holes: set[tuple[int, int]]) -> set[tuple[int, int]]:
    """Floor slab, ceiling slab and wall columns for one level.

    `holes` are cells where the floor and ceiling slabs must be omitted so a
    stairwell or the Gate Chamber void can pass vertically through them.
    Returns the set of open floor cells actually excavated on this level.
    """
    y = level["y"]
    regions = level["regions"]
    rng = random.Random(_seed(level["key"]))

    active = {(x, z) for (x, z) in plan.open if region_of(z) in regions}

    # Wall cells are the closed cells touching excavated floor (8-connected so
    # corners are sealed too) — this is what makes the envelope lava-tight.
    walls: set[tuple[int, int]] = set()
    for x, z in active:
        for dx in (-1, 0, 1):
            for dz in (-1, 0, 1):
                nx, nz = x + dx, z + dz
                if 0 <= nx < N and 0 <= nz < N and not plan.is_open(nx, nz):
                    walls.add((nx, nz))

    footprint = active | walls

    # Floor slab.  Public halls read differently from service spaces.
    for x, z in footprint:
        if (x, z) in holes:
            continue
        if (x, z) in walls:
            block = WALL_ACCENT
        elif region_of(z) == BAND and 30 <= x <= 60:
            block = FLOOR_HALL
        else:
            block = FLOOR_PUBLIC if (x, z) in active else FLOOR_SERVICE
        t.set(x, y, z, block)

    # Excavate the rooms.  This is not optional: a structure template only
    # removes what it explicitly places, so without an air column every
    # "room" generates as solid Nether rock with a decorative wall grid
    # buried in it.  The interior air IS the building.
    for x, z in active:
        t.clear((x, y + 1, z), (x, y + 6, z))

    # Ceiling slab.
    for x, z in footprint:
        if (x, z) in holes:
            continue
        t.set(x, y + 7, z, CEILING)

    # Wall columns, with age-cracking that increases with depth.
    crack_rate = {"deep_works": 0.22, "laboratories": 0.14, "concourse": 0.06,
                  "habitation": 0.10, "anchorage": 0.16}[level["key"]]
    for x, z in walls:
        for wy in range(y + 1, y + 7):
            block = WALL_CRACKED if rng.random() < crack_rate else WALL
            t.set(x, wy, z, block)

    # A course of packing rock behind the outermost wall ring, so the building
    # never presents a bare one-block skin to open lava.
    for x, z in walls:
        for dx in (-1, 0, 1):
            for dz in (-1, 0, 1):
                nx, nz = x + dx, z + dz
                if not (0 <= nx < N and 0 <= nz < N):
                    continue
                if (nx, nz) in footprint or (nx, nz) in holes:
                    continue
                for wy in range(y, y + 8):
                    t.set(nx, wy, nz, PACKING)

    return active


def build_doors(t: Template, plan: Plan, level: dict, program: dict, active: set[tuple[int, int]],
                skip: set[tuple[int, int]]) -> tuple[set[tuple[int, int]], set[tuple[int, int]]]:
    """Hang a door in every printed doorway inside this level's footprint.

    Derived levels re-partition the same lattice: the colony walled openings up
    and knocked others through repeatedly over four hundred years, which is why
    the plan is shared but the door set is not.
    """
    y = level["y"]
    rng = random.Random(0x1EA5 ^ _seed(level["key"]))
    room_kind: dict[tuple[int, int], str] = {}
    for num, (_name, kind) in program.items():
        for c in room_cells_in(plan, num, level["regions"]):
            room_kind[c] = kind
    walled_up: set[tuple[int, int]] = set()
    doored: set[tuple[int, int]] = set()

    for x, z, axis in plan.doors:
        if (x, z) not in active or (x, z) in skip:
            continue
        roll = rng.random()
        if roll < 0.12 and level["key"] != "concourse":
            # Walled up.  Solid, and it reads as a later blocking course.
            for wy in range(y + 1, y + 7):
                t.set(x, wy, z, WALL_CRACKED)
            walled_up.add((x, z))
            continue
        if roll < 0.30:
            continue  # left as an open archway
        neighbours = [room_kind.get((x + dx, z + dz)) for dx, dz in ((1, 0), (-1, 0), (0, 1), (0, -1))]
        secure = any(k in SECURE_KINDS for k in neighbours if k)
        facing = "east" if axis == "x" else "south"
        WS.door(t, x, y + 1, z, facing, DOOR_MAT)
        if secure:
            # Controlled access is expressed with a chiselled architrave, NOT
            # with an iron door.  An iron door in a generated structure needs
            # redstone the player has no way to supply, so it is not a secure
            # room, it is a room nobody can ever enter.
            for dx, dz in (((0, -1), (0, 1)) if axis == "x" else ((-1, 0), (1, 0))):
                for wy in range(y + 1, y + 4):
                    if solid_at(t, x + dx, wy, z + dz):
                        t.set(x + dx, wy, z + dz, WALL_CHISEL)
        doored.add((x, z))
    return walled_up, doored


def repair_circulation(t: Template, level: dict, active: set[tuple[int, int]],
                       walled_up: set[tuple[int, int]], doored: set[tuple[int, int]]) -> dict[str, int]:
    """Guarantee every excavated cell on this level is actually reachable.

    Four hundred years of re-partitioning is good fiction, but a blocking
    course that happens to be the only way into a nine-cell corridor stub is
    just an unreachable room.  This pass re-opens exactly the blockages that
    isolate something, and downgrades a door to an open archway where the
    pocket behind it is too small to be a room at all — the two conditions
    check_room_composition flags.
    """
    from collections import deque
    y = level["y"]
    reopened = 0
    demoted = 0

    def components(passable: set[tuple[int, int]]) -> list[set[tuple[int, int]]]:
        seen: set[tuple[int, int]] = set()
        out = []
        for start in passable:
            if start in seen:
                continue
            comp = {start}
            seen.add(start)
            q = deque([start])
            while q:
                cx, cz = q.popleft()
                for dx, dz in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                    n = (cx + dx, cz + dz)
                    if n in passable and n not in seen:
                        seen.add(n)
                        comp.add(n)
                        q.append(n)
            out.append(comp)
        return out

    # 1. A doored pocket smaller than a room becomes an archway instead.
    for comp in components(active - walled_up - doored):
        if len(comp) >= 4:
            continue
        for cx, cz in comp:
            for dx, dz in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                n = (cx + dx, cz + dz)
                if n in doored:
                    t.clear((n[0], y + 1, n[1]), (n[0], y + 2, n[1]))
                    doored.discard(n)
                    demoted += 1

    # 2. Re-open blocking courses until the level is one connected space.
    guard = 0
    while guard < 200:
        guard += 1
        comps = components(active - walled_up)
        if len(comps) <= 1:
            break
        comps.sort(key=len, reverse=True)
        main = comps[0]
        bridged = False
        for cell in sorted(walled_up):
            touches = set()
            for dx, dz in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                n = (cell[0] + dx, cell[1] + dz)
                for i, comp in enumerate(comps):
                    if n in comp:
                        touches.add(i)
            if len(touches) > 1 or (touches and 0 in touches and len(comps) > 1 and len(touches) == 1 and False):
                t.clear((cell[0], y + 1, cell[1]), (cell[0], y + 2, cell[1]))
                walled_up.discard(cell)
                reopened += 1
                bridged = True
                break
        if not bridged:
            break
    return {"reopened": reopened, "archways": demoted}


