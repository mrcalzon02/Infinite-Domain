def _seed(key: str) -> int:
    """Stable per-level seed.

    Python's built-in hash() for str is salted per process, so using it here
    made the generator emit a different building on every run.  A structure
    that cannot be regenerated byte-for-byte is not reviewable, so seeding is
    done with a fixed checksum instead.
    """
    return zlib.crc32(key.encode("utf-8"))


def region_of(z: int) -> str:
    if z <= 30:
        return NORTH
    if z <= 59:
        return BAND
    return SOUTH


