class Plan:
    def __init__(self, path: Path):
        raw = json.loads(path.read_text(encoding="utf-8"))
        self.grid = raw["grid"]
        self.open: set[tuple[int, int]] = {
            (x, z) for z in range(N) for x in range(N) if self.grid[z][x] == "."
        }
        self.doors = [(d["x"], d["z"], d["axis"]) for d in raw["doors"]]
        self.rooms = {
            int(k): {
                "cells": {(x, z) for x, z in v["cells"]},
                "bounds": v["bounds"],
                "label": tuple(v["label"]),
                "area": v["area"],
            }
            for k, v in raw["rooms"].items()
        }
        self.orphans = {(x, z) for x, z in raw["orphan_cells"]}

    def is_open(self, x: int, z: int) -> bool:
        return (x, z) in self.open


def room_cells_in(plan: Plan, room: int, regions: set[str]) -> set[tuple[int, int]]:
    return {(x, z) for x, z in plan.rooms[room]["cells"] if region_of(z) in regions}


def interior_of(cells: set[tuple[int, int]], plan: Plan) -> list[tuple[int, int]]:
    """Cells with open floor on all four sides — safe for freestanding furniture."""
    return sorted(
        c for c in cells
        if all(plan.is_open(c[0] + dx, c[1] + dz) for dx, dz in ((1, 0), (-1, 0), (0, 1), (0, -1)))
    )


def wall_adjacent_of(cells: set[tuple[int, int]], plan: Plan) -> list[tuple[int, int, str]]:
    """Open cells touching a wall, with the facing that points away from it."""
    out = []
    for x, z in sorted(cells):
        for (dx, dz), facing in (((0, -1), "south"), ((0, 1), "north"), ((-1, 0), "east"), ((1, 0), "west")):
            if not plan.is_open(x + dx, z + dz):
                out.append((x, z, facing))
                break
    return out


